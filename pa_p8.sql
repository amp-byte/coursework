-- EMPLOYEE TABLE FROM PROJECT 5
-- Create this table by copying any 10 rows from the table you created in project 5
-- using “create table from an existing table” technique. 

DROP TABLE EMPLOYEE;
CREATE TABLE EMPLOYEE (
  id INTEGER(10),
  first_name VARCHAR(10),
  last_name VARCHAR(10),
  email VARCHAR(20),
  emp_pass VARCHAR(15),
  salary INTEGER
);

CREATE SEQUENCE emp_id INCREMENT BY 1 START WITH 1;

DECLARE
 id INTEGER(10);
 fname VARCHAR(10);
 lname VARCHAR(10);
 stremail VARCHAR(20);
 epwd VARCHAR(15);
 sal INTEGER;

BEGIN
id := emp_id.NEXTVAL;

FOR i IN 1 ..500 LOOP
 fname := DBMS_RANDOM.string('u', ROUND(DBMS_RANDOM.value(1,10)));
 lname := DBMS_RANDOM.string('u', ROUND(DBMS_RANDOM.value(1,10)));
 stremail := DBMS_RANDOM.string('1',10)||'@'||DBMS_RANDOM.string('1',5)||'.'||DBMS_RANDOM.string('2',3);
 epwd := DBMS_RANDOM.string('x', ROUND(DBMS_RANDOM.value(8,15)));
 sal := ROUND(DBMS_RANDOM.value(low => 1, high => 100000));

INSERT INTO EMPLOYEE VALUES(i, fname, lname, stremail, epwd, sal);
END LOOP;
END;
/

SELECT *
FROM EMPLOYEE;

