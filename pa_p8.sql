-- STEP 4 // create procedure  (35’)
CREATE OR REPLACE PROCEDURE SPPUSERS 
(N IN NUMBER, TELE IN VARCHAR)
IS

BEGIN
DECLARE
A NUMBER:= 1;
I NUMBER:= 1;
TELE VARCHAR(50);
FIRSTNAME VARCHAR(50);
LASTNAME VARCHAR(50);
PASSWORD VARCHAR (50);

FOR A IN 1..N LOOP
	FIRSTNAME:= (SELECT first_name FROM BBT_USERS_TEMP WHERE ROW_NUMBER()= I);
	LASTNAME:= (SELECT last_name FROM BBT_USERS_TEMP WHERE ROW_NUMBER()= I);
	PASSWORD:= (SELECT emp_pass FROM BBT_USERS_TEMP WHERE ROW_NUMBER()= I);

	INSERT INTO PHONE_USERS
		VALUES(TELE, FIRSTNAME, LASTNAME, PASSWORD);

	I:= I + 1;
END LOOP;
END;
/

