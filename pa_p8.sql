-- STEP 3 // Create function(20’)
CREATE OR REPLACE FUNCTION KEYMAP(LASTNAME IN VARCHAR2)
RETURN VARCHAR2
IS
	EXTENSION VARCHAR2(4);

-- Use translate function to convert the lastname to extension
BEGIN
	EXTENSION:= TRANSLATE(EXTENSION,'ABC','222');
	EXTENSION:= TRANSLATE(EXTENSION,'DEF','333');
	EXTENSION:= TRANSLATE(EXTENSION,'GHI','444');
	EXTENSION:= TRANSLATE(EXTENSION,'JKL','555');
	EXTENSION:= TRANSLATE(EXTENSION,'MNO','666');
	EXTENSION:= TRANSLATE(EXTENSION,'PQRS','7777');
	EXTENSION:= TRANSLATE(EXTENSION,'TUV','888');
	EXTENSION:= TRANSLATE(EXTENSION,'WXYZ','9999');

	-- for names shorter than 4 characters, then use zeros as placeholders
	IF LENGTH(LASTNAME)<4 THEN
		FOR VAR IN 1..(4-LENGTH(LASTNAME))
		LOOP
			EXTENSION:= || '0';
		END LOOP;
	END IF;
END;
